  final dryRun = args.contains('--dry-run');
  print('====================================================');
  print('INVENTORY IMPORTER - DapitanStore (Dry Run: $dryRun)');
  print('====================================================');

  final dbPath = r'C:\Users\picar\AppData\Roaming\com.joyce.pos\joyce_pos_branch_dapitanstore_3293.db';

  if (!dryRun) {
    // Create safety backup
    final backupPath = '$dbPath.bak_${DateTime.now().millisecondsSinceEpoch}';
    File(dbPath).copySync(backupPath);
    print('Safety backup created at: $backupPath');
  }

  final db = sqlite3.open(dbPath);

  final existingRows = db.select('SELECT id, name, category, price, stock, active FROM products');
  final existingList = existingRows.map((r) => {
    'id': r['id'] as int,
    'name': (r['name'] as String).trim(),
    'category': (r['category'] as String).trim(),
    'price': (r['price'] as num).toDouble(),
    'stock': r['stock'] as int,
    'active': r['active'] as int,
  }).toList();

  print('Existing DB products: ${existingList.length}');
  print('Transcribed inventory items to process: ${inventoryData.length}');

  int matchedCount = 0;
  int insertedCount = 0;
  int pricePreservedCount = 0;
  int priceSetCount = 0;

  final Set<int> usedExistingIds = {};

  if (!dryRun) {
    db.execute('BEGIN TRANSACTION');
  }

  try {
    for (final item in inventoryData) {
      Map<String, dynamic>? match;

      // 1. Try alias exact match (case-insensitive)
      for (final alias in item.aliases) {
        final aNorm = alias.trim().toLowerCase();
        for (final ex in existingList) {
          if (usedExistingIds.contains(ex['id'])) continue;
          if ((ex['name'] as String).trim().toLowerCase() == aNorm) {
            match = ex;
            break;
          }
        }
        if (match != null) break;
      }

      // 2. Try item displayName or name match
      if (match == null) {
        final nameNorm = item.name.trim().toLowerCase();
        final dispNorm = item.displayName.trim().toLowerCase();
        for (final ex in existingList) {
          if (usedExistingIds.contains(ex['id'])) continue;
          final exNorm = (ex['name'] as String).trim().toLowerCase();
          if (exNorm == nameNorm || exNorm == dispNorm) {
            match = ex;
            break;
          }
        }
      }

      if (match != null) {
        usedExistingIds.add(match['id'] as int);
        matchedCount++;
        final existingPrice = match['price'] as double;
        // Per user rule: if item already has price in the existing database don't overwrite it
        final finalPrice = existingPrice > 0.0 ? existingPrice : item.defaultPrice;
        if (existingPrice > 0.0) {
          pricePreservedCount++;
        } else {
          priceSetCount++;
        }

        print('[MATCH] ID ${match['id']}: "${match['name']}" -> Stock: ${match['stock']} -> ${item.stock} | Price: P$existingPrice -> P$finalPrice (Preserved: ${existingPrice > 0.0})');

        if (!dryRun) {
          // Update name if existing name didn't have size details
          final newName = match['name'].toString().length < item.displayName.length ? item.displayName : match['name'];
          db.execute(
            'UPDATE products SET name = ?, stock = ?, price = ?, active = 1 WHERE id = ?',
            [newName, item.stock, finalPrice, match['id']],
          );
        }
      } else {
        insertedCount++;
        priceSetCount++;
        print('[NEW] "${item.displayName}" | Cat: ${item.category} | Stock: ${item.stock} | Price: P${item.defaultPrice}');

        if (!dryRun) {
          final now = DateTime.now().toIso8601String();
          db.execute(
            '''INSERT INTO products(name, barcode, category, price, cost, stock, low_stock, image, active, created_at)
               VALUES(?, '', ?, ?, 0.0, ?, 5, '', 1, ?)''',
            [item.displayName, item.category, item.defaultPrice, item.stock, now],
          );
        }
      }
    }

    if (!dryRun) {
      final now = DateTime.now().toIso8601String();
      db.execute(
        '''INSERT INTO audit_logs(timestamp, actor, role, action, entity_type, entity_id, summary, details_json)
           VALUES(?, 'Administrator', 'admin', 'IMPORT', 'inventory', 'all', 'Imported physical inventory counts from notepad images', ?)''',
        [now, jsonEncode({'matched': matchedCount, 'inserted': insertedCount, 'total': inventoryData.length})],
      );
      db.execute('COMMIT');
      print('DB TRANSACTION COMMITTED SUCCESSFULLY.');
    }
  } catch (e) {
    if (!dryRun) {
      db.execute('ROLLBACK');
      print('ERROR: DB TRANSACTION ROLLED BACK: $e');
    }
    rethrow;
  }

  print('\n---------------- SUMMARY ----------------');
  print('Total inventory items processed: ${inventoryData.length}');
  print('Matched existing products: $matchedCount');
  print('New products inserted: $insertedCount');
  print('Prices preserved (existing price > 0): $pricePreservedCount');
  print('Prices set (existing price was 0 or new): $priceSetCount');
  print('-----------------------------------------');

  // Also write unreadable CSV
  final unreadableFile = File(r'C:\Users\picar\Desktop\inventory\unreadable_inventory.csv');
  final csvContent = StringBuffer();
  csvContent.writeln('Image,Raw_Text,Reason,Suggested_Item');
  csvContent.writeln('20261026_144751.jpg,"SILVER SWAN CLA91","Ambiguous variant code CLA91 (unclear if classic, 91g pouch, or specific SKU)","Silver Swan Soy Sauce"');
  csvContent.writeln('20261026_144955.jpg,"San Rio 12 pcs.","Unspecified product type (only brand name San Rio written)","Sanrio Item / Handkerchief / Pouch"');
  csvContent.writeln('20261026_145021.jpg,"PRIDE POWDER STRAWBERRY (40g) -","Quantity count missing/blank on notepad","Pride Powder Strawberry 40g"');
  csvContent.writeln('20261026_145033.jpg,"PRIDE CALAMANSI (40g) -","Quantity count missing/blank on notepad","Pride Powder Calamansi 40g"');
  unreadableFile.writeAsStringSync(csvContent.toString());
  print('Created unreadable inventory CSV at: ${unreadableFile.path}');
}
